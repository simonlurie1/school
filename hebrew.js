// סדר מילון: sameFirst — כל המילים מתחילות באותה אות (משווים את האות השנייה)
const rank = w => plain(w).split('').map(c => ABC.indexOf(c));
const before = (a, b) => { const x = rank(a), y = rank(b); for (let i = 0; i < Math.min(x.length, y.length); i++) if (x[i] !== y[i]) return x[i] < y[i]; return x.length < y.length; };
function dictQ(sameFirst) {
  let ws;
  if (sameFirst) {
    const groups = {}; PIC.forEach(p => (groups[p.w[0]] = groups[p.w[0]] || []).push(p.w));
    const g = pick(Object.values(groups).filter(a => new Set(a.map(w => w[1])).size >= 3));
    const by2 = {}; shuffle(g).forEach(w => by2[w[1]] = by2[w[1]] || w); ws = shuffle(Object.values(by2)).slice(0, 4);
  } else {
    const by1 = {}; shuffle(PIC).forEach(p => by1[p.w[0]] = by1[p.w[0]] || p.w); ws = shuffle(Object.values(by1)).slice(0, 4);
  }
  const ans = ws.reduce((a, b) => before(a, b) ? a : b);
  return Q({ prompt: 'איזו מילה באה ראשונה לפי סדר האל"ף־בי"ת (כמו במילון)?', vis: '', opts: ws, ans,
    ex: `${ws.slice().sort((a, b) => before(a, b) ? -1 : 1).join(' ← ')}`, hint: sameFirst ? 'כל המילים מתחילות באותה אות, אז בודקים את האות השנייה.' : 'בודקים את האות הראשונה של כל מילה. מי מוקדמת יותר באל"ף־בי"ת?', data: { k: 'he-dict', ws } });
}

